export const GUIDE_DOC = `# Pen tools guide

Tap a section with the pen to select it, then tap **Edit section** to open
the writing workspace.

## The tools

- **Write** — ink flows onto the ruled lines. Words after your pen move
  forward and wrap, like a word processor for handwriting.
- **Insert space** — drag right inside a line to open horizontal room;
  drag left to close it again.
- **Blank lines** — drag downward to insert ruled lines for writing.
- **Erase** — touch a stroke to remove it.
- **Select** — tap handwriting to select it; drag to move it.

## Saving

Everything saves automatically. Press the back button or **◀ Library** to
return to your documents.

> Handwriting stays handwriting — nothing is converted unless you ask.
`;
